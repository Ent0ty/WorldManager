<?php

declare(strict_types=1);

namespace WorldManager\gamerule;

use function array_map;

/**
 * The values are the vanilla Bedrock rule names, which are also used as level.dat tag names.
 */
enum GameRule: string{
	case DO_DAYLIGHT_CYCLE = 'dodaylightcycle';
	case KEEP_INVENTORY = 'keepinventory';
	case PVP = 'pvp';
	case SHOW_DEATH_MESSAGES = 'showdeathmessages';
	case DO_MOB_LOOT = 'domobloot';
	case TNT_EXPLOSION_DROP_DECAY = 'tntexplosiondropdecay';
	case DROWNING_DAMAGE = 'drowningdamage';
	case FALL_DAMAGE = 'falldamage';
	case FIRE_DAMAGE = 'firedamage';
	case NATURAL_REGENERATION = 'naturalregeneration';
	case SHOW_COORDINATES = 'showcoordinates';
	case SHOW_DAYS_PLAYED = 'showdaysplayed';
	case SHOW_TAGS = 'showtags';

	public function getDefault(): bool{
		return match($this){
			self::KEEP_INVENTORY, self::TNT_EXPLOSION_DROP_DECAY, self::SHOW_DAYS_PLAYED => false,
			default => true,
		};
	}

	/**
	 * Health is regenerated by the server, PocketMine keeps the client-side rule disabled to prevent double regeneration.
	 */
	public function isSentToClient(): bool{
		return $this !== self::NATURAL_REGENERATION;
	}

	/**
	 * @return string[]
	 * @phpstan-return list<string>
	 */
	public static function getNames(): array{
		return array_map(static fn(self $rule): string => $rule->value, self::cases());
	}
}
